def tile(room, x, y):
  if x < 0 or x > 23 or y < 0 or y > 9:
    return "#"
  return ROOMS[room][y][x]

def room_ok():
  if len(ROOMS) != 6:
    return False
  for room in ROOMS:
    if len(room) != 10:
      return False
    for row in room:
      if len(row) != 24:
        return False
  return True
